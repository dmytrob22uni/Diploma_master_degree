using System;
using UnityEngine;
using Coursework_Master_Degree.Items.FFF.Jobs;

namespace Coursework_Master_Degree.ScriptableObjects.ObjectsToPrint
{
    /// <summary>
    /// Numeric baseline for one object. Time and filament are measured at the
    /// global reference layer height and speed, with a solid (100% infill)
    /// print. Object size is derived from the prefab bounds, not authored.
    /// </summary>
    [Serializable]
    public class ObjectToPrintPrintProfile
    {
        [Tooltip("Filament used by a solid (100% infill) print at the reference profile.")]
        [Min(0.0f)]
        public float FilamentMetersAt100PercentInfill = 10.0f;

        [Tooltip("Print time for a solid (100% infill) print at the reference profile.")]
        [Min(0.0f)]
        public float PrintTimeSecondsAt100PercentInfill = 3600.0f;

        [Tooltip("Geometry needs supports for acceptable overhangs.")]
        public bool SupportsRequired;

        [Tooltip("Share of the surface that overhangs; generated by the editor tool.")]
        [Range(0.0f, 100.0f)]
        public float SupportOverhangPercent;

        [Tooltip(
            "Fixed shell/wall thickness used by the scale estimate. " +
            "The shell is solid; the remaining volume uses the selected infill.")]
        [Min(0.0f)]
        public float WallThicknessMillimeters = 1.2f;
    }

    /// <summary>
    /// Gameplay requirements that are not part of the numeric print baseline.
    /// </summary>
    [Serializable]
    public class ObjectToPrintRequirements
    {
        public InfillPattern DefaultInfill = InfillPattern.Grid;
    }
}
